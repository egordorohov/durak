async def init_fake_players() -> None:
    """Seed bot profiles once. Uses Redis lock so only one worker runs this."""
    from .redis_client import get_redis
    r = await get_redis()
    if r:
        seeded = await r.set("durak:bots_seeded_v2", "1", nx=True, ex=3600)
        if not seeded:
            return  # another worker already did it

    pool = db_mod.get_pool()
    batch = 50
    for start in range(0, len(FAKE_PROFILES), batch):
        chunk = FAKE_PROFILES[start:start + batch]
        async with pool.acquire() as conn:
            async with conn.transaction():
                for fp in chunk:
                    await conn.execute(
                        "INSERT INTO users (id, name, username, coins) VALUES ($1, $2, NULL, 99999)"
                        " ON CONFLICT (id) DO NOTHING",
                        fp["id"], fp["name"],
                    )
                    losses = max(0, fp["games"] - fp["wins"])
                    await conn.execute(
                        """INSERT INTO stats (user_id, games, wins, losses, draws, streak, best_streak)
                           VALUES ($1, $2, $3, $4, 0, 0, 0)
                           ON CONFLICT (user_id) DO NOTHING""",
                        fp["id"], fp["games"], fp["wins"], losses,
                    )


