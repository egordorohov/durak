async def _sentinel_loop(fp: dict, hub, wait_timeout: float = 120) -> None:
    """Keeps one open 2-player room in the lobby.
    Only goes ready when a real player joins; if nobody joins after wait_timeout, recycles."""
    from .rooms import RoomSettings, Room, Player, send_state, _broadcast

    pid, name = fp["id"], fp["name"]
    await asyncio.sleep(random.uniform(2, 8))

    while True:
        ws = FakeWS()
        try:
            async with hub._lock:
                hub._evict(pid)
                code = secrets.token_urlsafe(6)[:8]
                while code in hub.rooms:
                    code = secrets.token_urlsafe(6)[:8]
                s = RoomSettings(bet=100, max_players=2, deck_size=36, mode="perevodnoy")
                room = Room(code=code, settings=s, private=False)
                hub.rooms[code] = room
                hub.profiles[pid] = {
                    "id": pid, "name": name, "username": None,
                    "coins": 99999, "card_skin": "classic",
                    "table_skin": "default", "emoji_pack": "classic",
                    "user_pack": "", "avatar_url": None, "owned": [],
                }
                p_obj = Player(pid=pid, name=name, ws=ws, coins=99999)
                room.players.append(p_obj)
                hub.user_room[pid] = code
                room.last_activity = time.time()

            hub.queue_room_list_broadcast()
            log.debug("sentinel %s opened room %s", name, code)

            # Wait for a real player
            deadline = time.time() + wait_timeout
            real_joined = False
            while time.time() < deadline:
                if hub.room_of(pid) is None:
                    break
                real_players = [p for p in room.players if p.pid not in FAKE_IDS]
                if real_players:
                    real_joined = True
                    break
                await asyncio.sleep(1.0)

            if not real_joined:
                async with hub._lock:
                    hub.user_room.pop(pid, None)
                    if room.code in hub.rooms and all(p.pid in FAKE_IDS for p in room.players):
                        hub.rooms.pop(room.code, None)
                hub.queue_room_list_broadcast()
                log.debug("sentinel %s: no real player, recycling", name)
                await asyncio.sleep(1)
                continue

            await asyncio.sleep(random.uniform(1.5, 3.0))
            if hub.room_of(pid) is None:
                continue
            room = await hub.mark_ready(pid)
            if room is None:
                continue
            from .rooms import send_state
            await send_state(room)

            deadline = time.time() + 60
            while time.time() < deadline:
                if room.state and room.state.phase == G.Phase.PLAYING:
                    break
                await asyncio.sleep(0.3)
            else:
                async with hub._lock:
                    hub.user_room.pop(pid, None)
                continue

            log.debug("sentinel %s: game started with real player", name)
            stop = asyncio.Event()

            def action(type_: str, **kwargs) -> None:
                if room.state is None or room.state.phase != G.Phase.PLAYING:
                    return
                try:
                    if type_ == "attack":
                        G.attack(room.state, pid, kwargs["card"])
                    elif type_ == "defend":
                        G.defend(room.state, pid, kwargs["attack"], kwargs["card"])
                    elif type_ == "transfer":
                        G.transfer(room.state, pid, kwargs["card"])
                    elif type_ == "take":
                        G.take(room.state, pid)
                    elif type_ == "done":
                        G.done(room.state, pid)
                    elif type_ == "pass":
                        G.pass_turn(room.state, pid)
                except G.GameError:
                    return
                from .rooms import _broadcast
                asyncio.create_task(_broadcast(room))

            await _run_bot_ai(lambda: room.state, action, stop, bot_pid=pid)
            stop.set()

            deadline = time.time() + 15
            while time.time() < deadline:
                if room.result_applied:
                    break
                if room.state and room.state.phase == G.Phase.FINISHED:
                    from .rooms import _broadcast
                    await _broadcast(room)
                    break
                await asyncio.sleep(0.3)

            async with hub._lock:
                hub.user_room.pop(pid, None)
                room.players = [p for p in room.players if p.pid != pid]
                if all(p.pid in FAKE_IDS for p in room.players):
                    hub.rooms.pop(room.code, None)
                    t = hub.turn_timers.pop(room.code, None)
                    if t:
                        t.cancel()
            hub.queue_room_list_broadcast()

        except Exception as e:
            log.exception("sentinel %s error: %s", name, e)
            async with hub._lock:
                hub.user_room.pop(pid, None)
        await asyncio.sleep(random.uniform(1, 3))


async def _player_loop(fp: dict, hub) -> None:
    if fp["id"] in _LOBBY_SENTINEL_IDS:
        return
    pid, name = fp["id"], fp["name"]
    await asyncio.sleep(random.uniform(5, 45))
    while True:
        try:
            if hub.room_of(pid) is None:
                await _play_one_game(pid, name, hub)
        except Exception as e:
            log.exception("fake player %s error: %s", name, e)
        await asyncio.sleep(random.uniform(20, 90))


async def start_fake_players(hub) -> None:
    try:
        await init_fake_players()
    except Exception as e:
        log.warning("init_fake_players failed (non-fatal): %s", e)

    sentinel_timeouts = [60, 100, 140]
    sentinel_list = [fp for fp in FAKE_PROFILES if fp["id"] in _LOBBY_SENTINEL_IDS]
    for fp, timeout in zip(sentinel_list, sentinel_timeouts):
        asyncio.create_task(_sentinel_loop(fp, hub, wait_timeout=timeout))
    for fp in _ACTIVE_PROFILES:
        if fp["id"] not in _LOBBY_SENTINEL_IDS:
            asyncio.create_task(_player_loop(fp, hub))
    log.info("fake players started: %d sentinels + %d active bots",
             len(sentinel_list), len(_ACTIVE_PROFILES) - len(sentinel_list))
